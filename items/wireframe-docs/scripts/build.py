#!/usr/bin/env python3
"""Render a wireframe-docs tree.md (markdown) into a standalone HTML wireframe.

Usage:
    python3 build.py <tree.md> [-o <out.html>]

Rules follow items/wireframe-docs/convention/tree-format.md (stdlib only).
Exit 0 on success; exit 1 with an error line on invalid input.
"""
import html
import re
import sys


def parse(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    page = None
    page_note = ""
    sections = []  # [(name, [comp, ...])], comp = {type, label, note, states}
    cur = None
    for raw in lines:
        line = raw.strip()
        m = re.match(r"^# Page:\s*(.+?)\s*$", line)
        if m:
            if page is not None:
                sys.stderr.write("error: more than one '# Page:' line\n")
                return None
            page = m.group(1)
            continue
        if page is not None and not sections and not page_note:
            m = re.match(r"^>\s*(.*)$", line)
            if m and m.group(1).strip():
                page_note = m.group(1).strip()
                continue
        m = re.match(r"^## Section:\s*(.+?)\s*$", line)
        if m:
            cur = (m.group(1), [])
            sections.append(cur)
            continue
        m = re.match(r"^-\s+`([^`]+)`\s+\*\*([^*]+)\*\*\s*(?:—\s*(.*))?$", line)
        if m:
            if cur is None:
                sys.stderr.write("error: component before any '## Section:'\n")
                return None
            ctype, label, meta = m.group(1).strip(), m.group(2).strip(), (m.group(3) or "").strip()
            note, states = "", ["default"]
            for part in meta.split("|"):
                part = part.strip()
                if part.lower().startswith("note:"):
                    note = part[5:].strip()
                elif part.lower().startswith("states:"):
                    states = [s.strip() for s in part[7:].split(",") if s.strip()] or ["default"]
            cur[1].append({"type": ctype, "label": label, "note": note, "states": states})
    if page is None:
        sys.stderr.write("error: missing '# Page:' line\n")
        return None
    if not sections:
        sys.stderr.write("error: no '## Section:' found\n")
        return None
    for name, comps in sections:
        if not comps:
            sys.stderr.write("error: section '%s' has no components\n" % name)
            return None
    return {"page": page, "note": page_note, "sections": sections}


CSS = """body{font-family:sans-serif;background:#f4f4f5;color:#18181b;margin:0;padding:32px}
.wire{max-width:900px;margin:0 auto;background:#fff;border:2px solid #18181b;padding:32px}
h1{margin:0 0 4px;font-size:24px}.pagenote{color:#52525b;margin:0 0 24px}
fieldset{border:2px dashed #a1a1aa;margin:0 0 24px;padding:16px}
legend{font-weight:bold;padding:0 8px}
.comp{border:1px solid #71717a;background:#fafafa;padding:10px 12px;margin:10px 0}
.comp .idx{display:inline-block;background:#18181b;color:#fff;font-size:12px;padding:2px 8px;margin-right:8px}
.comp .type{font-family:monospace;font-size:12px;color:#52525b}
.comp .label{font-weight:bold;margin:6px 0 2px}
.comp .note{font-size:13px;color:#52525b}
.chip{display:inline-block;border:1px solid #a1a1aa;font-size:11px;padding:1px 6px;margin:2px 4px 0 0}
footer{color:#71717a;font-size:12px;margin-top:16px}"""


def render(doc):
    e = html.escape
    out = ["<!DOCTYPE html>", "<html lang='vi'>", "<head><meta charset='utf-8'>",
           "<title>%s — wireframe</title>" % e(doc["page"]),
           "<style>%s</style></head><body><div class='wire'>" % CSS,
           "<h1>%s</h1>" % e(doc["page"])]
    if doc["note"]:
        out.append("<p class='pagenote'>%s</p>" % e(doc["note"]))
    idx = 0
    for name, comps in doc["sections"]:
        out.append("<fieldset><legend>Section: %s</legend>" % e(name))
        for c in comps:
            idx += 1
            out.append("<div class='comp'><span class='idx'>%02d</span>"
                       "<span class='type'>%s</span>"
                       "<div class='label'>%s</div>" % (idx, e(c["type"]), e(c["label"])))
            if c["note"]:
                out.append("<div class='note'>%s</div>" % e(c["note"]))
            out.append("<div>%s</div></div>" % "".join(
                "<span class='chip'>%s</span>" % e(s) for s in c["states"]))
        out.append("</fieldset>")
    total = sum(len(c) for _, c in doc["sections"])
    out.append("<footer>%d sections · %d components · generated by wireframe-docs build.py</footer>"
               % (len(doc["sections"]), total))
    out.append("</div></body></html>")
    return "\n".join(out)


def main(argv):
    if len(argv) < 2 or "-h" in argv or "--help" in argv:
        print("usage: python3 build.py <tree.md> [-o <out.html>]")
        return 2
    src = argv[1]
    dst = argv[argv.index("-o") + 1] if "-o" in argv else src.rsplit(".", 1)[0] + ".html"
    try:
        doc = parse(src)
    except FileNotFoundError:
        sys.stderr.write("error: file not found: %s\n" % src)
        return 1
    if doc is None:
        return 1
    with open(dst, "w", encoding="utf-8") as f:
        f.write(render(doc))
    total = sum(len(c) for _, c in doc["sections"])
    print("wrote %s (%d sections, %d components)" % (dst, len(doc["sections"]), total))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
